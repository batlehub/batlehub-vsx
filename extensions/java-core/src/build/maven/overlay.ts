// The overlay, if spike (a) leaves it in (RFC 0001 §4.2, §7): a *copy* of
// the active settings file with `<activeProfiles>` added, holding only what
// the import needs — `<profiles>`, `<activeProfiles>`, `<mirrors>`,
// `<servers>` — written 0600 under `.batlehub/java/` after the `.gitignore`
// line, never logged. Pure: the content; the glue does the rest.

const section = (xml: string, name: string): string | undefined =>
  new RegExp(`<${name}(?:\\s[^>]*)?>[\\s\\S]*?</${name}>`).exec(xml)?.[0];

export function overlayOf(settingsXml: string, profiles: string[]): string {
  const clean = settingsXml.replace(/<!--[\s\S]*?-->/g, "");
  const parts = ["profiles", "mirrors", "servers"]
    .map((n) => section(clean, n))
    .filter((s): s is string => !!s);
  const existing = [
    ...(section(clean, "activeProfiles") ?? "").matchAll(
      /<activeProfile>([^<]+)<\/activeProfile>/g,
    ),
  ].map((m) => m[1]!.trim());
  const all = [...new Set([...existing, ...profiles])];
  parts.push(
    `<activeProfiles>\n${all.map((p) => `    <activeProfile>${p}</activeProfile>`).join("\n")}\n  </activeProfiles>`,
  );
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by BatleHub Java from your Maven settings, for the language server's import only.
     It may carry credentials: it is gitignored, 0600, and removed by "Java: Remove BatleHub settings". -->
<settings xmlns="http://maven.apache.org/SETTINGS/1.2.0">
  ${parts.join("\n  ")}
</settings>
`;
}
