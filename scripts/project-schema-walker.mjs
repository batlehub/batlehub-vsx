#!/usr/bin/env node
// RFC 0006 §6.1: the key table `project-config.ts` walks, generated from
// extensions/java-core/schema/java-project.schema.json, so the editor's
// Problems rows, the engine's lines and the schema's own squiggles agree
// key by key. `--check` fails when the committed table is not what the
// schema gives (the `lint` job).
//
//   node scripts/project-schema-walker.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";

const SCHEMA = "extensions/java-core/schema/java-project.schema.json";
const OUT = "packages/java-rules/src/project-keys.ts";
const schema = JSON.parse(readFileSync(SCHEMA, "utf8"));

/** One leaf: what the walker checks. Item objects keep their properties' types. */
const leaf = (s) => {
  const out = {};
  if (s.enum) out.enum = s.enum;
  else out.type = s.type;
  if (s.pattern) out.pattern = s.pattern;
  if (s.type === "array")
    out.items =
      s.items.type === "object"
        ? {
            type: "object",
            required: s.items.required ?? [],
            properties: Object.fromEntries(
              Object.entries(s.items.properties).map(([k, v]) => [k, v.type === "array" ? "string[]" : v.type]),
            ),
          }
        : { type: s.items.type };
  if (s.description) out.description = s.description;
  return out;
};

const keys = {};
for (const [section, s] of Object.entries(schema.properties)) {
  if (s.type !== "object" || s.additionalProperties !== false) continue; // version, $schema, satellites (open)
  for (const [k, v] of Object.entries(s.properties)) keys[`${section}.${k}`] = leaf(v);
}

const text = `// Generated by scripts/project-schema-walker.mjs from
// extensions/java-core/schema/java-project.schema.json: do not edit by hand.
// The key table project-config.ts validates against (RFC 0006 §6.1).

export const PROJECT_KEYS = ${JSON.stringify(keys, null, 2)} as const;

export const PROJECT_SECTIONS = ${JSON.stringify(Object.keys(schema.properties).filter((k) => k !== "$schema" && k !== "version"))} as const;
`;
if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(OUT, "utf8");
  } catch {}
  if (committed !== text) {
    console.error(`${OUT} is not what ${SCHEMA} gives: run 'node scripts/project-schema-walker.mjs'`);
    process.exit(1);
  }
  console.log(`${Object.keys(keys).length} project.json keys in ${OUT}, current`);
} else {
  writeFileSync(OUT, text);
  console.log(`${Object.keys(keys).length} project.json keys → ${OUT}`);
}
